    doc = Document(DOC)
    chapter3(doc)
    chapter1(doc)
    chapter2(doc)
    chapter4(doc)
    apply_fixes(doc)
    doc.save(DOC)

    imgs = len(doc.element.body.findall(".//" + "{http://schemas.openxmlformats.org/drawingml/2006/wordprocessingDrawing}inline"))
