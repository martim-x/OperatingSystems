#!/bin/bash
# bat_02.sh — аналог bat_02.bat: имя скрипта, время изменения, полный путь
# Аналоги bat: %~nx0 (имя файла), %~t0 (дата изменения), %~f0 (полный путь)

echo "=== bat_02: параметры скрипта ==="
echo "Имя файла: $(basename "$0")"
echo "Изменён: $(stat -c '%y' "$0" | cut -d'.' -f1)"
echo "Полный путь: $(realpath "$0")"
