def chapter3(doc):
    sections = parse_chapter3(io.open(MD, encoding="utf-8").read())
    assert len(sections) == 11, f"гл.3: получено подразделов {len(sections)}"
    n_img = sum(1 for _, _, u in sections for k, _ in u if k == "img")
    n_cap = sum(1 for _, _, u in sections for k, _ in u if k == "cap")
    assert n_img == 56, f"гл.3: рисунков {n_img} (ожидалось 56)"
    print(f"гл.3: 11 подразделов, {n_img} рисунков / {n_cap} подписей")

    head = find_par(doc, "Отключение Secure Boot и загрузка live-Ubuntu", "3-head")
    app = find_par(doc, "АППАРАТНАЯ КОНФИГУРАЦИЯ", "3-end")
    pars = all_pars(doc)
    for p in pars[index_of(pars, head) + 1:index_of(pars, app)]:
        delete_par(p)

    anchor = head
    for num, name, units in sections:
        block = []
        if num > 1:
            block.append(("text", f"3.{num} {name}"))
        block.extend(units)
        anchor = add_block_after(anchor, block, doc)
    add_block_after(anchor, [("blank", "")], doc)
    print("гл.3 пересобрана")


