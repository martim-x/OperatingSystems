def strip_numbering(p):
    """Снимает автонумерацию с абзаца.

    Стили Глава_диплома и Раздел_диплома из образца несут numPr (numId=6),
    поэтому Word подставляет свой номер поверх номера, заданного в тексте:
    «5.8 4.1.4 Создание иерархии». Номера разделов и пунктов в отчёте
    проставляются текстом, значит автонумерация должна быть отключена.
    """
    pPr = p._p.get_or_add_pPr()
    for numPr in pPr.findall(docx.oxml.ns.qn("w:numPr")):
        pPr.remove(numPr)
    # Простое удаление numPr не помогает: нумерация наследуется от стиля.
    # Явный numId=0 означает «нумерация отключена» для этого абзаца.
    numPr = pPr.makeelement(docx.oxml.ns.qn("w:numPr"), {})
    ilvl = pPr.makeelement(docx.oxml.ns.qn("w:ilvl"), {docx.oxml.ns.qn("w:val"): "0"})
    numId = pPr.makeelement(docx.oxml.ns.qn("w:numId"), {docx.oxml.ns.qn("w:val"): "0"})
    numPr.append(ilvl)
    numPr.append(numId)
    pPr.append(numPr)
    return p

def para(text="", style=S_TEXT, align=None, indent=None, mono=False, size=None):
    p = doc.add_paragraph(style=style)
    if style in (S_CHAP, S_SEC):
        strip_numbering(p)
    if text:
        r = p.add_run(guillemet(text))
        if mono:
            r.font.name = "Courier New"
            r.font.size = Pt(size or 10)
