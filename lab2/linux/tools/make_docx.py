def guillemet(text):
    """Прямые двойные кавычки -> «ёлочки». Лапки и одинарные не трогаем."""
    out = []
    open_q = True
    for ch in text:
        if ch == '"':
            out.append("«" if open_q else "»")
            open_q = not open_q
        elif ch == "„":
            out.append("«")
        elif ch == "“":
            out.append("»")
        else:
            out.append(ch)
    return "".join(out)

