def apply_fixes(doc):
    n = 0
    for p in doc.paragraphs:
        t = p.text
        for old, new in FIXES:
            if old in t:
                t = t.replace(old, new)
                n += 1
        if t != p.text:
            set_text(p, t)
    print(f"текстовых правок применено: {n}")


