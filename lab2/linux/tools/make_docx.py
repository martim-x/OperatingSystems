SHRUNK = {}
def shrink(path, max_w=1400):
    """Уменьшенная копия снимка для вставки в docx (иначе файл раздувается
    до сотен мегабайт). Результат кэшируется, каждый снимок обрабатывается
    один раз."""
    key = (path, max_w)
    if key in SHRUNK:
        return SHRUNK[key]
    out = os.path.join(CACHE, os.path.basename(path))
    shutil.copy(path, out)
    subprocess.run(["sips", "-Z", str(max_w), out, "--out", out],
                   capture_output=True)
    SHRUNK[key] = out
    return out

def prune_media(path):
    """Удаляет из пакета docx неиспользуемые изображения.

    Копия образца (lab1.docx) весит 142 МБ из-за сотни старых снимков. После
    очистки тела документа они остаются в пакете как осиротевшие части, и
    файл не уменьшается. Здесь оставляются только те media, на которые реально
    ссылаются document.xml и колонтитулы.
    """
    import zipfile
    import re as _re
    src = zipfile.ZipFile(path)
    names = src.namelist()

    # какие rId использует содержимое
    used_rids = set()
    for part in names:
        if not _re.match(r"word/(document|header\d*|footer\d*)\.xml$", part):
            continue
        xml = src.read(part).decode("utf-8", "replace")
        used_rids |= set(_re.findall(r'r:embed="(rId\d+)"', xml))
        used_rids |= set(_re.findall(r'r:id="(rId\d+)"', xml))

    # rId -> имя media-файла
    keep_media = set()
    for part in names:
        if not _re.match(r"word/_rels/(document|header\d*|footer\d*)\.xml\.rels$", part):
            continue
        rels = src.read(part).decode("utf-8", "replace")
        for rid, target in _re.findall(r'Id="(rId\d+)"[^>]*Target="([^"]+)"', rels):
            if rid in used_rids and "media/" in target:
                keep_media.add("word/" + target.lstrip("/"))

    drop = {n for n in names if n.startswith("word/media/")} - keep_media

    # чистим и rels от удалённых картинок
    fixed = {}
    for part in names:
        if part in drop:
            continue
        data = src.read(part)
        if _re.match(r"word/_rels/(document|header\d*|footer\d*)\.xml\.rels$", part):
            txt = data.decode("utf-8")
            for rid, target in _re.findall(r'Id="(rId\d+)"[^>]*Target="([^"]+)"', txt):
                if "media/" in target and ("word/" + target.lstrip("/")) in drop:
                    txt = _re.sub(r'<Relationship[^>]*Id="%s"[^>]*/>' % rid, "", txt)
            data = txt.encode("utf-8")
        fixed[part] = data

    tmp = path + ".tmp"
    with zipfile.ZipFile(tmp, "w", zipfile.ZIP_DEFLATED) as out:
        for n in names:
            if n not in drop:
                out.writestr(n, fixed[n])
    src.close()
    os.replace(tmp, path)
    return len(drop)

def key_of(ptz):
    mm = re.match(r"^(.*п\.)(\d+)(?:\.\d+)?", ptz)
    if mm:
        return mm.group(1) + mm.group(2)
    if ptz.startswith("Л9"):
        return "Л9"
    return ptz

def parse(text):
    cmd, inp, out, mode = "", [], [], None
    for ln in text.splitlines():
        if ln.startswith("### КОМАНДА:"):
            cmd = ln.split(":", 1)[1].strip(); mode = "cmd"; continue
        if ln.startswith("### ВВОД:"):
            mode = "inp"; continue
        if mode == "cmd" and not ln.strip():
            mode = None; continue
        if mode == "inp":
            inp.append(ln); continue
        out.append(ln.rstrip())
    while out and not out[0]: out.pop(0)
    while out and not out[-1]: out.pop()
    return cmd, inp, out

