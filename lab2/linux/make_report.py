def key_of(ptz):
    # 'Л4-5 п.1.2' -> 'Л4-5 п.1'; 'Л8 п.2.1 (Linux)' -> 'Л8 п.2'; 'Л9 ...' -> 'Л9'.
    # Префикс уровня содержит цифры ('Л4-5'), поэтому отрезаем пункт от конца:
    # ищем последнюю точку и оставляем всё, что до неё плюс номер пункта.
    mm = re.match(r"^(.*п\.)(\d+)(?:\.\d+)?", ptz)
    if mm:
        return mm.group(1) + mm.group(2)
    if ptz.startswith("Л9"):
        return "Л9"
    return ptz

def load_rows():
    rows = []
    for lvl, mapping in m.LEVELS.items():
        td = f"{HERE}/выводы/{lvl}"
